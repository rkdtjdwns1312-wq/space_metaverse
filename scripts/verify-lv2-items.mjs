import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createClassroomServer } from '../server/app.js';
import { fillNewClass } from './class-setup.mjs';
import { SHOP, STREET, STREET_ID } from '../shared/config.js';
import { LV2_ITEMS } from '../shared/lv2-items.js';

const key = 'lv2-items-isolated-fixture-key';
const recipe = { ingredients: [{ id: 'space-food-card', quantity: 2 }], output: { id: 'spaceship-card' } };
const game = createClassroomServer({ teacherKey: key, studentHours: false, craftingRecipes: [recipe] });
const { port } = await game.listen();
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, hasTouch: true });
context.setDefaultTimeout(10000);
const page = await context.newPage();
const checks = [], errors = [];
const check = text => { checks.push(text); console.log(`LV2 ${checks.length}: ${text}`); };
page.on('pageerror', error => errors.push(error.message));
await mkdir('.local', { recursive: true });

const roomOf = () => [...game.store.rooms.values()][0];
const publish = player => game.io.to(player.socketId).emit('room:state', game.store.snapshot(roomOf(), player));
const card = id => SHOP.items.find(item => item.id === id);

try {
  await page.goto(`http://127.0.0.1:${port}`, { waitUntil: 'domcontentloaded' });
  await page.locator('#teacher-tab').click();
  await page.locator('#teacher-key').fill(key);
  await fillNewClass(page, ['LV2 검증 학생']);
  await page.locator('#teacher-form .submit').click();
  await page.locator('#lobby').waitFor({ state: 'hidden' });
  const room = roomOf();
  const player = [...room.players.values()][0];
  const shop = STREET.objects.find(object => object.kind === 'shop');
  const machine = STREET.objects.find(object => object.kind === 'crafting');
  Object.assign(player, { mapId: STREET_ID, x: shop.x, y: shop.y + shop.radius + 12, starShards: 1000, inventory: [] });
  publish(player);

  await page.locator('#world').focus();
  await page.keyboard.press('f');
  await page.locator('#shop-dialog').waitFor({ state: 'visible' });
  await page.locator('#shop-level-tabs [data-shop-level="2"]').click();
  const sale = LV2_ITEMS.filter(item => item.forSale !== false);
  assert.equal(sale.length, 9);
  assert.equal(await page.locator('#shop-buy-list li.item').count(), 9);
  assert.equal(await page.locator('#shop-buy-list img.item-art').count(), 9);
  assert.equal(await page.locator('#shop-buy-list img.item-art').evaluateAll(async images => { await Promise.all(images.map(image => image.decode())); return images.every(image => image.naturalWidth > 0); }), true);
  assert.ok(sale.every(item => item.level === 2 && item.art.startsWith('/assets/items/lv2/')));
  check('LV2 상점 탭에 판매 가능 9종이 표시되고 LV2 이미지 9개가 모두 decode됨');

  const saleItemId = 'asteroid-card';
  const saleItem = page.locator(`#shop-buy-list li[data-item-id="${saleItemId}"]`);
  const price = card(saleItemId).price;
  await saleItem.locator('button.buy').click();
  await page.locator('#shop-shards').filter({ hasText: (1000 - price).toLocaleString('ko-KR') }).waitFor();
  await page.locator('#shop-tab-sell').click();
  const sell = page.locator(`#shop-sell-list li[data-item-id="${saleItemId}"]`);
  await sell.filter({ hasText: '가진 개수 1' }).waitFor();
  const quote = card(saleItemId).sellPrice;
  await sell.locator('button.sell').click();
  const expectedBalance = 1000 - price + quote;
  await page.locator('#shop-shards').filter({hasText:expectedBalance.toLocaleString('ko-KR')}).waitFor();
  await sell.waitFor({state:'detached'});
  assert.equal(player.starShards,expectedBalance);
  assert.equal(player.inventory.some(item=>item.id===saleItemId),false);
  check('LV2 구매 11·판매 3을 실제 버튼으로 검증');
  const knownCatalog = SHOP.items.filter(item => item.id !== saleItemId);
  const firstPageItems = knownCatalog.filter(item => item.id !== 'spaceship-card').slice(0, 20);
  const secondPageItems = [knownCatalog.find(item => item.id === 'spaceship-card'), ...knownCatalog.filter(item => item.id !== 'spaceship-card').slice(20, 26)].filter(Boolean);
  const knownBagItems = [...firstPageItems, ...secondPageItems];
  assert.ok(knownBagItems.length >= 21);
  player.inventory = knownBagItems.map(item => ({ id: item.id, quantity: 1 }));
  publish(player);
  await page.locator('#shop-close').click();
  await page.locator('#dock-inventory').click();
  await page.locator('#inventory-dialog').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#bag-list li').count(), 20);
  assert.equal(await page.locator('.inventory-page-tab').count(), 2);
  await page.locator('.inventory-page-tab').nth(1).click();
  assert.equal(await page.locator('#bag-list li').count(), 7);
  const secondPageItem = page.locator('#bag-list li[data-item-id="spaceship-card"]');
  assert.equal(await secondPageItem.count(), 1);
  await secondPageItem.locator('.slot-btn').click();
  await page.locator('#bag-detail .item-info').click();
  await page.locator('#item-info-dialog').waitFor({ state: 'visible' });
  assert.match(await page.locator('#item-info-title').innerText(), /우주선/);
  await page.locator('#item-info-dialog [data-close="item-info-dialog"]').click();
  check('가방 40종 한도 fixture에서 20개/7개로 2페이지가 나뉘고 2페이지 LV2 아이템 정보가 열림');

  await page.locator('[data-close="inventory-dialog"]').click();
  Object.assign(player, { mapId: STREET_ID, x: machine.x, y: machine.y + 55, inventory: [{ id: 'space-food-card', quantity: 2 }], starShards: 7 });
  publish(player);
  await page.locator('#interact-prompt').filter({hasText:'별빛 조합기'}).waitFor();
  await page.locator('#world').focus();
  await page.keyboard.press('f');
  await page.locator('#crafting-dialog').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#crafting-bag button[data-item-id="space-food-card"]').count(), 1);
  await page.locator('#crafting-bag button[data-item-id="space-food-card"]').click();
  await page.locator('#crafting-bag button[data-item-id="space-food-card"]').click();
  await page.locator('#crafting-submit').click();
  await page.locator('#crafting-note').filter({ hasText: '조합 성공' }).waitFor();
  assert.equal(player.starShards, 6);
  assert.equal(player.inventory.find(item => item.id === 'spaceship-card')?.quantity, 1);
  assert.equal(player.inventory.find(item => item.id === 'space-food-card'), undefined);
  check('fixture 전용 space-food-card 2개 → spaceship-card 조합이 별 파편 1개를 소비하고 성공함');

  player.inventory = [{ id: 'space-food-card', quantity: 1 }]; player.starShards = 6; publish(player);
  await page.locator('#crafting-close').click();
  await page.locator('#world').focus(); await page.keyboard.press('f');
  await page.locator('#crafting-dialog').waitFor({ state: 'visible' });
  await page.locator('#crafting-bag button[data-item-id="space-food-card"]').click();
  await page.locator('#crafting-submit').click();
  await page.locator('#crafting-note').filter({ hasText: '실패' }).waitFor();
  assert.equal(player.starShards, 5); assert.deepEqual(player.inventory, [{ id: 'space-food-card', quantity: 1 }]);
  await page.locator('#crafting-close').click();
  const noRecipe = await page.request.get(`http://127.0.0.1:${port}/data/crafting-recipes.json`);
  assert.equal(noRecipe.status(), 404);
  assert.equal((await page.request.get(`http://127.0.0.1:${port}/server/crafting-recipes.js`)).status(),404);
  check('조합 실패는 별 파편1개만 차감하고 재료를 보존, 비밀 레시피와 서버 모듈 HTTP 경로는 404');

  player.role = 'student'; // 격리 테스트의 같은 세션을 학생 권한으로 검증합니다.
  player.avatar.level = 1; player.avatar.xp = 14; player.starShards = 0; player.inventory = [{ id: 'moon-rabbit-card', quantity: 1 }]; player.rabbitDraw = null; player.rabbitUsedDay = null; player.lastItemUseAt = 0; publish(player);
  await page.locator('#dock-inventory').click();
  await page.locator('.inventory-page-tab').first().click();
  await page.locator('#bag-list .slot-btn').click();
  await page.locator('#bag-detail .use').click();
  await page.locator('#draw-start').click();
  await page.locator('#draw-spread .draw-card').first().waitFor();
  assert.equal(player.inventory.find(item => item.id === 'moon-rabbit-card'), undefined);
  assert.equal(player.rabbitDraw.cards.length, 54);
  assert.equal(await page.locator('#draw-spread .draw-card').count(),54);
  const index = player.rabbitDraw.cards.findIndex(card => card.reward.kind === 'xp'&&card.reward.amount===10);
  assert.ok(index>=0);
  await page.locator('#draw-spread .draw-card').nth(index).click();
  await page.locator('#draw-spread .revealed').waitFor();
  assert.equal(player.avatar.xp, 15); assert.equal(player.starShards, 9); assert.equal(player.rabbitDraw,null);
  check('54장 실제 뽑기에서 LV1 XP14에 XP10 보상: XP15, 초과 별 파편9 지급');
  await page.locator('#draw-close').click();
  await page.locator('[data-close="inventory-dialog"]').click();
  Object.assign(player,{inventory:[{id:'moon-rabbit-card',quantity:1}],rabbitDraw:null,rabbitUsedDay:null,lastItemUseAt:0});publish(player);
  await page.locator('#dock-inventory').click();await page.locator('#bag-list .slot-btn').click();await page.locator('#bag-detail .use').click();await page.locator('#draw-start').click();
  await page.locator('#draw-spread .draw-card').first().waitFor();
  const itemIndex=player.rabbitDraw.cards.findIndex(c=>c.reward.kind==='item'&&c.reward.itemId==='android-card');
  await page.locator('#draw-spread .draw-card').nth(itemIndex).click();await page.locator('#draw-spread .revealed').waitFor();
  assert.equal(player.inventory.find(i=>i.id==='android-card')?.quantity,1);
  check('안드로이드 뽑기 보상이 인벤토리로 지급됨');

  await page.screenshot({ path: '.local/verify-lv2-items-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.local/verify-lv2-items-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  const report = { checks, errors, screenshots: ['.local/verify-lv2-items-desktop.png', '.local/verify-lv2-items-mobile.png'] };
  await writeFile('.local/verify-lv2-items-report.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  await writeFile('.local/verify-lv2-items-report.json', JSON.stringify({ checks, errors, failure: error.stack }, null, 2));
  throw error;
} finally {
  await context.close().catch(() => {});
  await browser.close();
  await game.close();
}

import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {createClassroomServer} from '../server/app.js';
import {fillNewClass} from './class-setup.mjs';

const key=randomBytes(32).toString('hex');
const game=createClassroomServer({teacherKey:key,studentHours:false});
const address=await game.listen(),url=`http://127.0.0.1:${address.port}`;
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
const errors=[];
try{
  const teacher=await browser.newPage({viewport:{width:1440,height:900}});teacher.on('pageerror',e=>errors.push(e.message));
  await teacher.goto(url);
  assert.equal(await teacher.locator('#lobby h2').textContent(),'우주 교실');
  assert.equal(await teacher.locator('#student-tab').textContent(),'학생 접속하기');
  const wide=await teacher.evaluate(()=>{const card=document.querySelector('#lobby').getBoundingClientRect(),button=document.querySelector('#student-form .submit').getBoundingClientRect();return {card:card.width,offset:button.left+button.width/2-card.left-card.width/2,over:document.documentElement.scrollWidth-innerWidth,background:getComputedStyle(document.querySelector('.map-wrap'),'::before').backgroundImage,subtitle:getComputedStyle(document.querySelector('#lobby>.muted')).fontSize};});
  assert.ok(wide.card>700&&wide.over<=0&&wide.background.includes('lobby-milky-way.png')&&Math.abs(wide.offset)<=2);
  assert.equal(wide.subtitle,'30px');
  assert.equal(await teacher.locator('#lobby>.muted').textContent(),'별빛 아래, 우리의 우주 공간');
  assert.match(await teacher.locator('#lobby h2').evaluate(title=>getComputedStyle(title).fontFamily),/Jua/);
  await teacher.locator('#student-hours-note').filter({hasText:'테스트 기간 제한 없음'}).waitFor();
  assert.equal(await teacher.locator('.lobby-hours').innerText(),'서버 오픈시간 오전 7시 ~ 오후 10시\n학생 접속: 테스트 기간 제한 없음');
  assert.equal(await teacher.locator('.lobby-credit').textContent(),'제작자 우주ssam');
  assert.equal(await teacher.locator('#student-form .submit').textContent(),'입장하기');
  assert.equal(await teacher.locator('.welcome-mark').count(),0);
  assert.ok(await teacher.locator('#join-code').evaluate(input=>parseFloat(getComputedStyle(input).fontSize)>=17));
  assert.ok(await teacher.locator('#pin-help').evaluate(help=>parseFloat(getComputedStyle(help).fontSize)>=14));
  await teacher.locator('#teacher-tab').click();
  const teacherOffset=await teacher.evaluate(()=>{const card=document.querySelector('#lobby').getBoundingClientRect(),button=document.querySelector('#teacher-form .submit').getBoundingClientRect();return button.left+button.width/2-card.left-card.width/2;});
  assert.ok(Math.abs(teacherOffset)<=2);
  assert.doesNotMatch(await teacher.locator('#teacher-form .submit').textContent(),/[✦↗]/);
  assert.ok(await teacher.locator('#teacher-key').evaluate(input=>parseFloat(getComputedStyle(input).fontSize)>=17));
  assert.ok(await teacher.locator('#choose-open-class').evaluate(button=>parseFloat(getComputedStyle(button).fontSize)>=16));
  assert.equal(await teacher.locator('#open-code').isVisible(),true);
  assert.equal(await teacher.locator('#saved-classes-button').isVisible(),true);
  await teacher.locator('#teacher-key').fill(key);
  await fillNewClass(teacher,['가람']);
  await teacher.locator('#teacher-form .submit').click();await teacher.locator('#lobby').waitFor({state:'hidden'});
  await teacher.locator('#vitals-hud').waitFor({state:'visible'});
  assert.match(await teacher.locator('#vitals-hud').innerText(),/HP 999\/999[\s\S]*MP 999\/999/);
  const room=[...game.store.rooms.values()][0];
  const student=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});student.on('pageerror',e=>errors.push(e.message));
  await student.goto(url);
  const narrow=await student.evaluate(()=>{const card=document.querySelector('#lobby').getBoundingClientRect(),button=document.querySelector('#student-form .submit').getBoundingClientRect();return {card:card.width,offset:button.left+button.width/2-card.left-card.width/2,over:document.documentElement.scrollWidth-innerWidth,button:button.bottom,subtitle:getComputedStyle(document.querySelector('#lobby>.muted')).fontSize};});
  assert.ok(narrow.card<=390&&narrow.over<=0&&narrow.button<=844&&Math.abs(narrow.offset)<=2);
  assert.equal(narrow.subtitle,'24px');
  await student.locator('#join-code').fill(room.code);await student.locator('#nickname').fill('가람');await student.locator('#student-pin').fill('1234');
  await student.locator('#student-form .submit').click();await student.locator('#lobby').waitFor({state:'hidden'});
  if(await student.locator('#password-offer-dialog').evaluate(dialog=>dialog.open))await student.locator('#password-offer-no').click();
  await student.locator('#tutorial-dialog').waitFor({state:'visible'});
  assert.match(await student.locator('#tutorial-title').textContent(),/걸어볼까요/);
  for(let i=0;i<5;i++)await student.locator('#tutorial-next').click();
  assert.match(await student.locator('#tutorial-title').textContent(),/자유롭게/);
  await student.locator('#tutorial-next').click();await student.locator('#tutorial-dialog').waitFor({state:'hidden'});
  const vitalsLayout=await student.evaluate(()=>{const hud=document.querySelector('#vitals-hud').getBoundingClientRect(),toast=document.querySelector('#toast');toast.textContent='3초 뒤에 다시 사용할 수 있어요';toast.hidden=false;const notice=toast.getBoundingClientRect();return {hudTop:hud.top,noticeBottom:notice.bottom,barHeight:document.querySelector('.vitals-bar').getBoundingClientRect().height,labelSize:getComputedStyle(document.querySelector('.vitals-label')).fontSize};});
  assert.ok(vitalsLayout.noticeBottom<=vitalsLayout.hudTop-4&&vitalsLayout.barHeight>=15&&parseFloat(vitalsLayout.labelSize)>=19);
  await student.screenshot({path:'.local/hud-toast-mobile.png'});
  assert.equal([...room.players.values()].find(player=>player.nickname==='가람').tutorialCompleted,true);
  await student.reload();await student.locator('#lobby').waitFor({state:'hidden'});
  assert.equal(await student.locator('#tutorial-dialog').evaluate(dialog=>dialog.open),false);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({desktop:wide.card,mobile:narrow.card,background:true,tutorialCompleted:true,errors}));
}finally{await browser.close();await game.close();}

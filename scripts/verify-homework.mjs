import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {createClassroomServer} from '../server/app.js';
import {PLAZA_ID} from '../shared/config.js';
const key=randomBytes(32).toString('hex'),game=createClassroomServer({teacherKey:key,studentHours:false});
const address=await game.listen(),url='http://127.0.0.1:'+address.port;
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
const errors=[],checks=[];
const check=text=>{checks.push(text);console.log(text);};
let room;
async function reposition(page,player,x,y){
  Object.assign(player,{x,y,mapId:PLAZA_ID,input:{x:0,y:0,at:0}});
  game.io.to(player.socketId).emit('room:state',game.store.snapshot(room,player));
  await page.waitForTimeout(100);
}
async function interact(page,label){
  await page.locator('#interact-object').filter({hasText:label}).waitFor();
  await page.locator('#touch-interact').click();
}
try{
  const teacher=await browser.newPage({viewport:{width:1440,height:960}});teacher.on('pageerror',e=>errors.push(e.message));
  await teacher.goto(url);await teacher.locator('#teacher-tab').click();await teacher.locator('#teacher-key').fill(key);
  await teacher.locator('#allowed-names').fill('가람');await teacher.locator('#teacher-form .submit').click();await teacher.locator('#lobby').waitFor({state:'hidden'});
  room=[...game.store.rooms.values()][0];const teacherPlayer=[...room.players.values()].find(p=>p.role==='teacher');
  const student=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});student.on('pageerror',e=>errors.push(e.message));
  await student.goto(url);await student.locator('#join-code').fill(room.code);await student.locator('#nickname').fill('가람');await student.locator('#student-pin').fill('1234');
  await student.locator('#student-form .submit').click();await student.locator('#lobby').waitFor({state:'hidden'});
  const studentPlayer=[...room.players.values()].find(p=>p.role==='student');
  assert.match(await student.locator('#dock-avatar').textContent(),/내정보/);
  assert.match(await student.locator('#dock-tasks').textContent(),/과제/);
  assert.match(await student.locator('#dock-inventory').textContent(),/가방/);
  check('내정보·과제·가방을 휴대폰 하단에서 따로 볼 수 있음');
  await reposition(teacher,teacherPlayer,790,850);
  await interact(teacher,'오늘의 시간표');await teacher.locator('#temple-dialog').waitFor({state:'visible'});
  assert.deepEqual(await teacher.locator('.timetable-table thead th').allTextContents(),['교시','월','화','수','목','금']);
  assert.equal(await teacher.locator('.timetable-table tbody tr').count(),6);
  await teacher.getByRole('textbox',{name:'월요일 1교시 과목'}).fill('우주과학');
  await teacher.locator('#temple-save').click();await teacher.locator('#toast').filter({hasText:'시간표를 저장했어요'}).waitFor();
  assert.equal(room.temple.schedule[0][0],'우주과학');
  await teacher.locator('#temple-close').click();
  await reposition(student,studentPlayer,790,850);
  await interact(student,'오늘의 시간표');await student.locator('.timetable-table').waitFor();
  assert.match(await student.locator('.timetable-table').textContent(),/우주과학/);
  assert.equal(await student.locator('.timetable-table input').count(),0);
  await student.locator('#temple-close').click();
  check('교사가 월~금 1~6교시 표를 저장하고 학생은 읽기 전용으로 봄');
  await reposition(teacher,teacherPlayer,760,650);
  await interact(teacher,'오늘의 알림장');await teacher.locator('#temple-editor').fill('별 관찰 기록하기\n내일은 체육복 입기');
  await teacher.locator('#temple-task-flags input').first().check();
  assert.equal(await teacher.locator('#temple-task-flags input:checked').count(),1);
  await teacher.locator('#temple-save').click();await teacher.locator('#temple-content small').filter({hasText:'과제'}).waitFor();
  await teacher.locator('#temple-close').click();
  await reposition(student,studentPlayer,760,650);
  await interact(student,'오늘의 알림장');
  assert.equal(await student.getByRole('button',{name:'과제로 가져오기'}).count(),1);
  await student.getByRole('button',{name:'과제로 가져오기'}).click();
  await student.getByRole('button',{name:'가져왔어요'}).waitFor();
  await student.locator('#temple-close').click();
  await student.locator('#dock-tasks').click();await student.locator('#tasks-dialog').waitFor({state:'visible'});
  assert.match(await student.locator('#my-tasks').textContent(),/별 관찰 기록하기/);
  await student.getByRole('button',{name:'과제완료'}).click();
  await student.locator('#my-tasks-empty').waitFor({state:'visible'});
  await student.locator('#tasks-close').click();
  check('체크한 알림장 한 줄만 개인 과제로 가져와 완료하면 목록에서 사라짐');
  await reposition(student,studentPlayer,260,520);
  await interact(student,'과제안드로메다');await student.locator('#assignment-dialog').waitFor({state:'visible'});
  assert.deepEqual(await student.locator('#assignment-weeks button').allTextContents(),['이번 주','지난주','2주 전']);
  await student.locator('#assignment-items button').first().click();
  assert.match(await student.locator('#assignment-completed').textContent(),/가람/);
  await student.locator('#assignment-weeks button').nth(1).click();
  assert.match(await student.locator('#assignment-items').textContent(),/과제가 없어요/);
  await student.locator('#assignment-close').click();
  await student.locator('#assignment-dialog').waitFor({state:'hidden'});
  await student.waitForFunction(()=>document.activeElement?.id==='world');
  check('과제안드로메다에 최근 3주와 과제별 완료 학생이 표시됨');
  assert.deepEqual(errors,[]);
}finally{await browser.close();await game.close();}
console.log(JSON.stringify({checks:checks.length,errors}));
